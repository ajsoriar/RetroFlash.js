'use strict';
/* Builds swf-extractor-core.js, the extractor's self-contained copy of the project modules it reuses (the SWF
   reader and the bitmap, shape, morph, font and sound decoders). Run it whenever one of those modules changes:
     node demo/swf-asset-extractor/build-core.js          writes the bundle
     node demo/swf-asset-extractor/build-core.js --check  exits with 1 when the bundle is out of date
   The modules run inside one function with a private global object, so the page's own window gets only
   window.SWFExtractorCore; a RetroFlash player on the same page is not affected. Node 16+, no dependencies. */
const fs = require('fs');
const path = require('path');

const here = __dirname;
const src = path.join(here, '..', '..', 'src');
const target = path.join(here, 'swf-extractor-core.js');
// Load order: the reader, then each module after the ones it uses (as in src/modules.json).
const MODULES = ['swf-reader.js', 'core/base.js', 'core/math.js', 'render/geometry.js', 'render/morph.js', 'display/bitmaps.js', 'audio/codecs.js', 'text/fonts.js'];

function bundle() {
  const parts = MODULES.map((file) => '// ---- src/' + file + ' ----\n' + fs.readFileSync(path.join(src, file), 'utf8').replace(/\r\n/g, '\n').trim() + '\n');
  return [
    '/* SWF Asset Extractor core: GENERATED by build-core.js from RetroFlashJS_WORK/src (' + MODULES.join(', ') + ').',
    '   Do not edit by hand; run `node demo/swf-asset-extractor/build-core.js` after changing those modules. */',
    '(function (host) {',
    '  \'use strict\';',
    '  // The modules attach SWFReader and RetroFlashModules to this object instead of the page\'s window; it',
    '  // forwards the few browser objects the bitmap decoder reads from its global.',
    '  var window = {',
    '    document: host.document, URL: host.URL, Image: host.Image,',
    '    createImageBitmap: typeof host.createImageBitmap === \'function\' ? host.createImageBitmap.bind(host) : undefined',
    '  };',
    '  var globalThis = window;',
    parts.join('\n'),
    '  host.SWFExtractorCore = Object.freeze({ SWFReader: window.SWFReader, modules: window.RetroFlashModules });',
    '})(typeof window !== \'undefined\' ? window : globalThis);',
    ''
  ].join('\n');
}

const code = bundle();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== code) {
    console.error('swf-extractor-core.js is out of date: run node demo/swf-asset-extractor/build-core.js');
    process.exitCode = 1;
  } else {
    console.log('swf-extractor-core.js is up to date');
  }
} else {
  fs.writeFileSync(target, code);
  console.log('wrote ' + path.relative(process.cwd(), target) + ' (' + (Buffer.byteLength(code) / 1024).toFixed(1) + ' KiB, ' + MODULES.length + ' modules)');
}
